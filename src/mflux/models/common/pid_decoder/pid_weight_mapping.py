def convert_checkpoint(pth_path: str) -> dict[str, mx.array]:
    """Load a released PiD .pth checkpoint and remap it onto PidNet's attribute paths.

    Returns a flat {mflux_attribute_path: mx.array} dict, ready for `tree_unflatten`
    into a PidNet's parameters. Conv2d weights (4D) are transposed from PyTorch's
    (out, in, kh, kw) to MLX's (out, kh, kw, in); everything else passes through unchanged
    (WeightTransforms.transpose_conv2d_weight no-ops on non-4D tensors).
    """
    state_dict = torch.load(pth_path, map_location="cpu", weights_only=True)
    state_dict = state_dict.get("state_dict", state_dict) if isinstance(state_dict, dict) else state_dict

    weights: dict[str, mx.array] = {}
    for key, tensor in state_dict.items():
        target = PID_WEIGHT_MAPPING[key]
        array = _to_mx_array(tensor)
        weights[target] = WeightTransforms.transpose_conv2d_weight(array)
    return weights


def _to_mx_array(tensor: torch.Tensor) -> mx.array:
    """bf16 tensors can't go through numpy directly (no native numpy bf16) -- reinterpret the raw
    bits as uint16 and mx.view back to bfloat16 (the same lossless trick SafetensorsReader.py uses
    for BF16-typed safetensors), instead of upcasting to float32. PidNet is the *distilled*
    checkpoint's own inference dtype; upcasting doubles load memory (observed: enough to cause real
    memory pressure just loading the ~5.2GB checkpoint) and drifts every layer from the released
    numerics the reference decode was validated against.
    """
    if tensor.dtype == torch.bfloat16:
        return mx.view(mx.array(tensor.contiguous().view(torch.uint16).numpy()), mx.bfloat16)
    return mx.array(tensor.numpy())
