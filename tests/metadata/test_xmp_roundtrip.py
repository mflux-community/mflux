"""Fast, hermetic regression tests for XMP read-back.

These pin the behavior fixed by the closing-tag construction bug in
``MetadataReader.read_xmp_metadata``. Before the fix, every field in the
``else`` branch (everything except description/creator/rights) built a
malformed closing tag ``</<ns:name>``. ``str.index`` never found it, raised
``ValueError``, and the reader swallowed it and returned ``None`` for *every*
image with XMP metadata. The first field to hit that branch is
``<xmp:CreatorTool>``, so the whole read failed early.

The pre-existing ``test_metadata.py`` only exercises the EXIF path (and is
``@pytest.mark.slow``), which is why this regression went unnoticed. These
tests are fast: they build an XMP packet, embed it in a real in-memory PNG,
and read it straight back.
"""

import os
import tempfile
from pathlib import Path

from PIL import Image

from mflux.utils.metadata_builder import MetadataBuilder
from mflux.utils.metadata_reader import MetadataReader


def _make_png_with_metadata(metadata: dict) -> Path:
    """Write a small PNG and embed the given metadata, returning its path."""
    fd, temp_path = tempfile.mkstemp(suffix=".png")
    path = Path(temp_path)
    # Close and overwrite with a real (tiny) image so embed_metadata can reopen it.
    os.close(fd)
    Image.new("RGB", (8, 8), (10, 20, 30)).save(path)
    MetadataBuilder.embed_metadata(metadata, path)
    return path


def test_read_xmp_roundtrip_returns_full_populated_dict():
    """A full metadata dict must round-trip to a populated (non-None) dict.

    On the buggy reader this returned ``None`` because the first ``else``-branch
    field (``<xmp:CreatorTool>``) built the closing tag ``</<xmp:CreatorTool>``,
    ``str.index`` raised ``ValueError``, and the except-clause returned ``None``.
    """
    metadata = {
        "prompt": "a serene mountain lake at dawn",
        "model": "dev",
        "seed": 42,
        "steps": 4,
        "guidance": 3.5,
        "generation_time": 12.34,
        "mflux_version": "1.2.3",
    }
    path = _make_png_with_metadata(metadata)
    try:
        xmp = MetadataReader.read_xmp_metadata(path)

        # The core regression assertion: not None, and actually populated.
        assert xmp is not None, "read_xmp_metadata returned None (the bug this PR fixes)"
        assert isinstance(xmp, dict) and xmp, "XMP dict should be populated, not empty"

        # The field that triggered the early failure must be present and correct.
        assert "creator_tool" in xmp, "creator_tool is the first else-branch field; its absence means the early failure"
    finally:
        path.unlink(missing_ok=True)


def test_read_xmp_roundtrip_pins_each_field_value():
    """Neighbor / counter-example: pin the actual value of every field.

    This ensures the test fails if closing tags are mismatched per field (not
    merely "the read didn't crash"). Each value is asserted exactly, so a
    truncated or cross-field slice would be caught.
    """
    metadata = {
        "prompt": "a serene mountain lake at dawn",
        "model": "dev",
        "seed": 42,
        "steps": 4,
        "guidance": 3.5,
        "generation_time": 12.34,
        "mflux_version": "1.2.3",
    }
    path = _make_png_with_metadata(metadata)
    try:
        xmp = MetadataReader.read_xmp_metadata(path)
        assert xmp is not None

        # Fields via the description/creator/rights branches.
        assert xmp["description"] == "a serene mountain lake at dawn"
        assert xmp["creator"] == "MFLUX"
        assert xmp["rights"] == "AI Generated Content"

        # Fields via the (previously broken) else branch. Each exact value pins
        # that the closing tag was located correctly and the slice is tight.
        assert xmp["creator_tool"] == "MFLUX 1.2.3"
        assert xmp["category"] == "ART"
        assert xmp["credit"] == "Generated by MFLUX"
        assert xmp["seed"] == "42"
        assert xmp["steps"] == "4"
        assert xmp["guidance"] == "3.5"
        assert xmp["model"] == "dev"
        assert xmp["generation_time"] == "12.34"
    finally:
        path.unlink(missing_ok=True)
